export type CountryRankingEntry = {
  rank: number
  country: string
  value?: string
}

export type CountryRanking = {
  id: string
  label: string
  entries: CountryRankingEntry[]
}

type RankingRow = readonly [country: string, value?: string]

function ranked(rows: readonly RankingRow[]): CountryRankingEntry[] {
  return rows.map(([country, value], index) => ({ rank: index + 1, country, value }))
}

